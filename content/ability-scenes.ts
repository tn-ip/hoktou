import { line } from "@/lib/text";
import type { Abilities, Choice, Scene, Stats, YearId } from "@/lib/types";

function choice(
  id: string,
  zh: string,
  en: string,
  detailZh: string,
  detailEn: string,
  ability: Partial<Abilities>,
  effects: Partial<Stats>,
): Choice {
  return {
    id,
    label: line(zh, en),
    detail: line(detailZh, detailEn),
    effects,
    ability,
  };
}

function card(
  id: string,
  year: YearId,
  kickerZh: string,
  kickerEn: string,
  titleZh: string,
  titleEn: string,
  focusZh: string,
  focusEn: string,
  bodyZh: string,
  bodyEn: string,
  options: Choice[],
): Scene {
  return {
    id,
    year,
    kicker: line(kickerZh, kickerEn),
    title: line(titleZh, titleEn),
    focus: line(focusZh, focusEn),
    body: () => line(bodyZh, bodyEn),
    choices: () => options,
  };
}

