function opt(
  id: string,
  zh: string,
  en: string,
  detailZh: string,
  detailEn: string,
  effects: Partial<Stats>,
  flags?: Partial<Flags>,
): Choice {
  return {
    id,
    label: line(zh, en),
    detail: line(detailZh, detailEn),
    effects,
    ...(flags ? { flags } : {}),
  };
}

function card(
  id: string,
  year: YearId,
  kickerZh: string,
  kickerEn: string,
  titleZh: string,
  titleEn: string,
  focusZh: string,
  focusEn: string,
  bodyZh: string,
  bodyEn: string,
  options: Choice[],
): Scene {
  return {
    id,
    year,
    kicker: line(kickerZh, kickerEn),
    title: line(titleZh, titleEn),
    focus: line(focusZh, focusEn),
    body: () => line(bodyZh, bodyEn),
    choices: () => options,
  };
}

